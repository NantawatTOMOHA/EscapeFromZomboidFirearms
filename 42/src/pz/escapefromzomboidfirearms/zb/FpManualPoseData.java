package pz.escapefromzomboidfirearms.zb;

import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import zombie.gameStates.ChooseGameInfo;

/**
 * Demand-loaded Tarkov first-person pose and hand tracks for manual weapon actions
 * (bolt/pump cycling, round-by-round reloads, cylinder/breech closing, unloads; W10 manualeye),
 * generated by tools/manual_actions.py into media/viewpoint/TW_ManualPoses.bin.
 * Kept separate from TW_FpPoses.bin so magazine reloads, patrol, inspect and launchers stay byte-identical.
 */
public final class FpManualPoseData {
    static final String RESOURCE = "media/viewpoint/TW_ManualPoses.bin";
    static final byte[] MAGIC = {'T', 'W', 'M', 'P', 'P', 'O', 'S', 'E'};
    static final int VERSION = 2;
    private static final int MAX_BYTES = 16 * 1024 * 1024, MAX_COUNT = 65536;
    private static FpManualPoseData cached;
    private static boolean attempted;
    private static volatile Map<FpPoseData.Track, RoundTrack> loadedRounds = Collections.emptyMap();
    static volatile String status = "not loaded";

    static final class RoundTrack {
        static final int STRIDE = 37;
        final int side;
        final boolean hasProp;
        final int frames;
        private final float[] data;

        RoundTrack(int side, boolean hasProp, int frames, float[] data) {
            this.side = side;
            this.hasProp = hasProp;
            this.frames = frames;
            this.data = data;
        }

        double leave(double u) {
            double x = Math.max(0, Math.min(1, u)) * Math.max(frames - 1, 0);
            int k = Math.min((int) x, frames - 1), j = Math.min(k + 1, frames - 1);
            double t = x - k;
            return data[k * STRIDE] * (1 - t) + data[j * STRIDE] * t;
        }

        double[] hand(double u, boolean female) {
            return sampleRigid(u, female ? 13 : 1);
        }

        double[] prop(double u) {
            return sampleRigid(u, 25);
        }

        private double[] sampleRigid(double u, int off) {
            double x = Math.max(0, Math.min(1, u)) * Math.max(frames - 1, 0);
            int k = Math.min((int) x, frames - 1), j = Math.min(k + 1, frames - 1);
            double t = x - k;
            double[] a = matrix(k * STRIDE + off);
            return t <= 0 ? a : FpPose.interp(a, matrix(j * STRIDE + off), t);
        }

        private double[] matrix(int base) {
            double[] m = new double[16];
            for (int i = 0; i < 12; i++) {
                m[i] = data[base + i];
            }
            m[15] = 1;
            return m;
        }
    }

    final int fps;
    final List<FpPoseData.Track> tracks;
    final Map<String, FpPoseData.Track> aliases;
    final Map<FpPoseData.Track, RoundTrack> rounds;

    private FpManualPoseData(int fps, List<FpPoseData.Track> tracks, Map<String, FpPoseData.Track> aliases,
                             Map<FpPoseData.Track, RoundTrack> rounds) {
        this.fps = fps;
        this.tracks = Collections.unmodifiableList(tracks);
        this.aliases = Collections.unmodifiableMap(aliases);
        this.rounds = Collections.unmodifiableMap(rounds);
    }

    static RoundTrack round(FpPoseData.Track t) {
        if (t == null) {
            return null;
        }
        FpManualPoseData d = cached != null ? cached : (attempted ? null : get());
        return (d != null ? d.rounds : loadedRounds).get(t);
    }

    static synchronized FpManualPoseData get() {
        if (attempted) {
            return cached;
        }
        attempted = true;
        try {
            ChooseGameInfo.Mod mod = ChooseGameInfo.getModDetails("EscapeFromZomboidFirearms");
            if (mod == null) {
                status = "mod not registered";
                return null;
            }
            for (String root : new String[] {mod.getVersionDir(), mod.getCommonDir()}) {
                if (root == null || root.isEmpty()) {
                    continue;
                }
                Path p = Path.of(root, RESOURCE);
                if (Files.isRegularFile(p)) {
                    cached = load(p);
                    if (cached != null) {
                        status = "ok";
                    }
                    return cached;
                }
            }
            status = "missing " + RESOURCE;
        } catch (Throwable t) {
            status = "failed: " + t;
            System.out.println("[TWZB] manual pose data failed: " + t);
        }
        return cached;
    }

    public static FpManualPoseData load(Path path) {
        try {
            long size = Files.size(path);
            if (size < 20 || size > MAX_BYTES) {
                status = "refused: manual pose resource size " + size;
                return null;
            }
            FpManualPoseData out = parse(Files.readAllBytes(path));
            status = "ok";
            return out;
        } catch (Exception e) {
            status = "refused: " + e;
            return null;
        }
    }

    static FpManualPoseData parse(byte[] raw) throws IOException {
        if (raw == null || raw.length < 20 || raw.length > MAX_BYTES) {
            throw new IOException("manual pose resource length " + (raw == null ? -1 : raw.length));
        }
        if (!Arrays.equals(Arrays.copyOfRange(raw, 0, 8), MAGIC)) {
            throw new IOException("bad manual pose magic");
        }
        ByteBuffer b = ByteBuffer.wrap(raw, 8, raw.length - 8).order(ByteOrder.LITTLE_ENDIAN);
        int version = b.getInt();
        if (version != VERSION) {
            throw new IOException("manual pose version " + version);
        }
        int fps = b.getInt();
        if (fps < 1 || fps > 240) {
            throw new IOException("manual pose fps " + fps);
        }
        int nt = count(b);
        List<FpPoseData.Track> tracks = new ArrayList<>(nt);
        for (int k = 0; k < nt; k++) {
            String name = text(b);
            int flags = b.getInt();
            float seconds = finite(b.getFloat());
            int frames = count(b);
            if (frames < 1 || (flags & FpPoseData.T_MANUAL) == 0) {
                throw new IOException("invalid manual track " + name);
            }
            int stride = 12 + ((flags & FpPoseData.T_GOALS) != 0 ? 6 : 0) + ((flags & FpPoseData.T_HANDS) != 0 ? 24 : 0);
            float[] data = new float[frames * stride];
            for (int i = 0; i < data.length; i++) {
                data[i] = finite(b.getFloat());
            }
            for (int frame = 0; frame < frames; frame++) {
                double[] pose = new double[16];
                int base = frame * stride;
                for (int i = 0; i < 12; i++) {
                    pose[i] = data[base + i];
                }
                pose[15] = 1;
                rigid(pose, "manual pose " + name);
                if ((flags & FpPoseData.T_HANDS) != 0) {
                    for (int side = 0; side < 2; side++) {
                        double[] hand = new double[16];
                        int offset = base + 12 + ((flags & FpPoseData.T_GOALS) != 0 ? 6 : 0) + side * 12;
                        for (int i = 0; i < 12; i++) {
                            hand[i] = data[offset + i];
                        }
                        hand[15] = 1;
                        rigid(hand, "manual hand " + name);
                    }
                }
            }
            tracks.add(new FpPoseData.Track(name, flags, seconds, frames, data));
        }
        int na = count(b);
        Map<String, FpPoseData.Track> aliases = new HashMap<>(na * 2);
        for (int k = 0; k < na; k++) {
            String clip = text(b);
            int idx = b.getInt();
            if (idx < 0 || idx >= tracks.size()) {
                throw new IOException("manual alias " + clip + " -> " + idx);
            }
            aliases.put(clip, tracks.get(idx));
        }
        int nr = count(b);
        Map<FpPoseData.Track, RoundTrack> rounds = new HashMap<>(nr * 2);
        for (int k = 0; k < nr; k++) {
            int idx = b.getInt();
            int side = Byte.toUnsignedInt(b.get());
            int hasProp = Byte.toUnsignedInt(b.get());
            int frames = count(b);
            if (idx < 0 || idx >= tracks.size() || (side != 0 && side != 1) || (hasProp != 0 && hasProp != 1)
                    || frames != tracks.get(idx).frames) {
                throw new IOException("invalid manual round track " + idx);
            }
            float[] data = new float[frames * RoundTrack.STRIDE];
            for (int i = 0; i < data.length; i++) {
                data[i] = finite(b.getFloat());
            }
            String rname = tracks.get(idx).name;
            for (int frame = 0; frame < frames; frame++) {
                int base = frame * RoundTrack.STRIDE;
                if (data[base] < -1e-4f || data[base] > 1.0001f) {
                    throw new IOException("invalid round leave weight " + rname);
                }
                for (int off : new int[] {1, 13, 25}) {
                    double[] m = new double[16];
                    for (int i = 0; i < 12; i++) {
                        m[i] = data[base + off + i];
                    }
                    m[15] = 1;
                    rigid(m, "manual round " + rname);
                }
            }
            rounds.put(tracks.get(idx), new RoundTrack(side, hasProp == 1, frames, data));
        }
        if (b.hasRemaining()) {
            throw new IOException(b.remaining() + " trailing bytes in manual poses");
        }
        FpManualPoseData out = new FpManualPoseData(fps, tracks, aliases, rounds);
        loadedRounds = out.rounds;
        return out;
    }

    private static void rigid(double[] m, String name) throws IOException {
        for (int i = 0; i < 3; i++) {
            for (int j = 0; j < 3; j++) {
                double dot = m[i] * m[j] + m[i + 4] * m[j + 4] + m[i + 8] * m[j + 8];
                if (Math.abs(dot - (i == j ? 1 : 0)) > 2e-4) {
                    throw new IOException("non-rigid " + name);
                }
            }
        }
        if (Math.abs(GripIK.dot(GripIK.cross(new double[] {m[0], m[4], m[8]}, new double[] {m[1], m[5], m[9]}),
                new double[] {m[2], m[6], m[10]}) - 1) > 2e-4) {
            throw new IOException("reflected " + name);
        }
    }

    private static int count(ByteBuffer b) throws IOException {
        int n = b.getInt();
        if (n < 0 || n > MAX_COUNT) {
            throw new IOException("count " + n);
        }
        return n;
    }

    private static float finite(float v) throws IOException {
        if (!Float.isFinite(v)) {
            throw new IOException("non-finite value");
        }
        return v;
    }

    private static String text(ByteBuffer b) throws IOException {
        int n = Short.toUnsignedInt(b.getShort());
        if (n > b.remaining()) {
            throw new IOException("string length " + n);
        }
        byte[] s = new byte[n];
        b.get(s);
        return new String(s, StandardCharsets.UTF_8);
    }
}
